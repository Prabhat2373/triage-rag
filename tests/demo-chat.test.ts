import assert from 'node:assert/strict';
import test from 'node:test';
import { POST } from '../src/app/api/chat/route';
import { demoIncidents, findDemoEvidence } from '../src/features/demo/incidents';
import { readChatEvents } from '../src/features/chat/stream-events';

function demoRequest(query: string, previousQuestion?: string) {
  return new Request('http://localhost/api/chat', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ query, previousQuestion, sessionId: 1 }),
  });
}

test('every demo chat reply is generated by Gemini, with sample evidence when relevant', async (context) => {
  for (const name of ['DEMO_MODE', 'GOOGLE_GENERATIVE_AI_API_KEY']) {
    const original = process.env[name];
    context.after(() => {
      if (original === undefined) delete process.env[name];
      else process.env[name] = original;
    });
  }
  process.env.DEMO_MODE = 'true';
  delete process.env.GOOGLE_GENERATIVE_AI_API_KEY;
  const unavailable = await POST(demoRequest('How are you?'));
  assert.equal(unavailable.status, 503);

  process.env.GOOGLE_GENERATIVE_AI_API_KEY = 'test-key';
  const fetchMock = context.mock.method(globalThis, 'fetch', async (_input: unknown, init?: RequestInit) => {
    const request = JSON.parse(String(init?.body));
    const prompt = JSON.parse(request.contents.at(-1).parts[0].text);
    const chunk = { candidates: [{ content: { role: 'model', parts: [{ text: `Gemini reply to: ${prompt.query}` }] }, finishReason: 'STOP' }] };
    return new Response(`data: ${JSON.stringify(chunk)}\n\n`, { headers: { 'Content-Type': 'text/event-stream' } });
  });

  const cases = [
    { query: 'Invoice export failed', codes: ['TKT-9001'] },
    { query: 'Give me list of recent incidents', codes: ['TKT-9001', 'TKT-9002', 'TKT-9003', 'TKT-9004', 'TKT-9005'], recent: true },
    { query: 'Show the 2 latest resolved incidents', codes: ['TKT-9001', 'TKT-9002'], recent: true },
    { query: 'Anything else?', previousQuestion: 'Invoice export failed', codes: ['TKT-9001'] },
    { query: 'How are you?', codes: [] },
    { query: 'What can you do?', codes: [] },
    { query: 'What is RAG?', codes: [] },
    { query: 'Who is the PM of India?', codes: [] },
    { query: 'Email attachments are corrupted', codes: [] },
  ];

  for (const { query, previousQuestion, codes, recent } of cases) {
    const response = await POST(demoRequest(query, previousQuestion));
    assert.equal(response.status, 200);
    assert.ok(response.body);
    const events = [];
    for await (const event of readChatEvents(response.body)) events.push(event);
    const [evidence, answer, done] = events;
    assert.equal(evidence?.type, 'evidence');
    assert.deepEqual(evidence.sources.map(({ ticketCode }) => ticketCode), codes);
    const modelRequest = JSON.parse(String(fetchMock.mock.calls.at(-1)?.arguments[1]?.body));
    const prompt = JSON.parse(modelRequest.contents.at(-1).parts[0].text);
    assert.equal(prompt.retrieval, recent ? 'recent_incidents' : 'incident_search');
    assert.deepEqual(prompt.incidents.map(({ ticketCode }: { ticketCode: string }) => ticketCode), codes);
    if (recent) {
      assert.ok(evidence.sources.every(({ sampleDate }) => sampleDate));
      const dates = evidence.sources.map(({ sampleDate }) => sampleDate);
      assert.deepEqual(dates, [...dates].sort().reverse());
    }
    assert.deepEqual(answer, { type: 'text', text: `Gemini reply to: ${query}` });
    assert.equal(done?.type, 'done');
  }
  assert.equal(fetchMock.mock.callCount(), cases.length);
});

test('every demo record has a unique ID and can be retrieved by title and incident code', () => {
  assert.equal(demoIncidents.length, 56);
  assert.equal(new Set(demoIncidents.map(({ ticketCode }) => ticketCode)).size, demoIncidents.length);
  for (const { ticketCode, title } of demoIncidents) {
    assert.equal(findDemoEvidence(title)[0]?.ticketCode, ticketCode, title);
    assert.deepEqual(findDemoEvidence(`How was ${ticketCode} resolved?`).map((source) => source.ticketCode), [ticketCode]);
  }
});
